import { useMemo, useState, type FormEvent } from 'react';
import { useNavigate, Link } from 'react-router-dom';
import { Badge, Button, Card, Field, Input, PageHeader, Select, Textarea } from '../components/ui.js';
import { validateConfig } from '../lib/validation.js';
import { createSession } from '../lib/session.js';
import { generateQuestionSet } from '../lib/apiClient.js';
import { upsertSession } from '../lib/storage.js';
import type { ExperienceLevel, InterviewConfig, InterviewType, ResponseMode } from '../lib/types.js';
import { useToast } from '../state/toast.js';

const ROLES = [
  'Software Engineer',
  'Frontend Engineer',
  'Backend Engineer',
  'Data Analyst',
  'Data Scientist',
  'Product Manager',
  'UX Designer',
  'Marketing Manager',
  'Sales Executive',
  'Customer Support Specialist',
  'Project Manager',
];

const TYPE_LABELS: { value: InterviewType; label: string }[] = [
  { value: 'hr', label: 'HR & introduction' },
  { value: 'behavioral', label: 'Behavioral' },
  { value: 'technical', label: 'Technical' },
  { value: 'project', label: 'Project discussion' },
  { value: 'situational', label: 'Situational judgment' },
  { value: 'role', label: 'Role-specific' },
  { value: 'mixed', label: 'Mixed interview' },
];

const EXPERIENCE_LABELS: { value: ExperienceLevel; label: string }[] = [
  { value: 'entry', label: 'Entry (0-2 years)' },
  { value: 'mid', label: 'Mid (2-5 years)' },
  { value: 'senior', label: 'Senior (5-9 years)' },
  { value: 'lead', label: 'Lead / Staff (10+ years)' },
];

export default function InterviewSetup() {
  const navigate = useNavigate();
  const { push } = useToast();

  const [role, setRole] = useState('');
  const [experience, setExperience] = useState<ExperienceLevel>('mid');
  const [industry, setIndustry] = useState('');
  const [type, setType] = useState<InterviewType>('mixed');
  const [difficulty, setDifficulty] = useState<'easy' | 'medium' | 'hard'>('medium');
  const [questionCount, setQuestionCount] = useState(5);
  const [durationMinutes, setDurationMinutes] = useState(30);
  const [mode, setMode] = useState<ResponseMode>('typed');
  const [jobDescription, setJobDescription] = useState('');
  const [resumeText, setResumeText] = useState('');
  const [followUps, setFollowUps] = useState(true);

  const [issues, setIssues] = useState<string[]>([]);
  const [generating, setGenerating] = useState(false);
  const [preview, setPreview] = useState<{ source: 'ai' | 'fallback'; model: string | null; note: string; count: number } | null>(null);

  const config: InterviewConfig = useMemo(
    () => ({
      role,
      experience,
      industry,
      type,
      difficulty,
      questionCount,
      durationMinutes,
      mode,
      jobDescription,
      resumeText,
      followUps,
    }),
    [role, experience, industry, type, difficulty, questionCount, durationMinutes, mode, jobDescription, resumeText, followUps],
  );

  const jdWords = jobDescription.trim() ? jobDescription.trim().split(/\s+/).length : 0;
  const resumeWords = resumeText.trim() ? resumeText.trim().split(/\s+/).length : 0;

  async function handleGenerate(event: FormEvent) {
    event.preventDefault();
    setPreview(null);
    const validation = validateConfig(config);
    if (!validation.ok) {
      setIssues(validation.issues);
      return;
    }
    setIssues([]);
    setGenerating(true);
    try {
      const result = await generateQuestionSet(validation.value);
      setPreview({ source: result.source, model: result.model, note: result.note, count: result.questions.length });
      const session = createSession(validation.value, result.questions, result.source === 'ai');
      const save = upsertSession(session);
      if (!save.ok) {
        push(save.error, 'error');
        return;
      }
      push(
        result.source === 'ai'
          ? `Interview plan generated by ${result.model ?? 'the AI provider'}.`
          : result.note || 'Using the built-in fallback question bank.',
        result.source === 'ai' ? 'success' : 'warning',
      );
      navigate(`/interview/${session.id}`);
    } finally {
      setGenerating(false);
    }
  }

  return (
    <div>
      <PageHeader
        title="Interview setup"
        subtitle="Configure a plan, generate questions, then start the session."
        actions={
          <Link to="/dashboard" className="btn-ghost">
            Cancel
          </Link>
        }
      />

      <form onSubmit={handleGenerate} noValidate className="grid gap-6 lg:grid-cols-3">
        <div className="space-y-5 lg:col-span-2">
          <Card className="p-5">
            <h2 className="mb-4 text-sm font-semibold uppercase tracking-wide text-ink-faint">Target role</h2>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field label="Job role" htmlFor="role" error={findIssue(issues, 'role')} required>
                <Input
                  id="role"
                  list="role-options"
                  value={role}
                  onChange={(e) => setRole(e.target.value)}
                  placeholder="e.g. Backend Engineer"
                />
                <datalist id="role-options">
                  {ROLES.map((r) => (
                    <option key={r} value={r} />
                  ))}
                </datalist>
              </Field>

              <Field label="Experience level" htmlFor="experience" required>
                <Select
                  id="experience"
                  value={experience}
                  onChange={(e) => setExperience(e.target.value as ExperienceLevel)}
                >
                  {EXPERIENCE_LABELS.map((opt) => (
                    <option key={opt.value} value={opt.value}>
                      {opt.label}
                    </option>
                  ))}
                </Select>
              </Field>

              <Field label="Industry / domain" htmlFor="industry" hint="Optional - e.g. Fintech, Healthcare">
                <Input id="industry" value={industry} onChange={(e) => setIndustry(e.target.value)} placeholder="Fintech" />
              </Field>

              <Field label="Interview type" htmlFor="type" required>
                <Select id="type" value={type} onChange={(e) => setType(e.target.value as InterviewType)}>
                  {TYPE_LABELS.map((opt) => (
                    <option key={opt.value} value={opt.value}>
                      {opt.label}
                    </option>
                  ))}
                </Select>
              </Field>
            </div>
          </Card>

          <Card className="p-5">
            <h2 className="mb-4 text-sm font-semibold uppercase tracking-wide text-ink-faint">Session format</h2>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field label="Difficulty" htmlFor="difficulty" required>
                <Select
                  id="difficulty"
                  value={difficulty}
                  onChange={(e) => setDifficulty(e.target.value as 'easy' | 'medium' | 'hard')}
                >
                  <option value="easy">Easy - warm-up</option>
                  <option value="medium">Medium - realistic</option>
                  <option value="hard">Hard - stretch</option>
                </Select>
              </Field>

              <Field label="Interview type note" htmlFor="type-note" hint="Mixed interviews blend question types">
                <Input id="type-note" value={TYPE_LABELS.find((t) => t.value === type)?.label ?? ''} readOnly />
              </Field>

              <Field
                label="Number of questions"
                htmlFor="count"
                error={findIssue(issues, 'questionCount')}
                required
              >
                <Input
                  id="count"
                  type="number"
                  min={3}
                  max={20}
                  value={questionCount}
                  onChange={(e) => setQuestionCount(Number(e.target.value))}
                />
              </Field>

              <Field label="Session duration (minutes)" htmlFor="duration" error={findIssue(issues, 'durationMinutes')} required>
                <Input
                  id="duration"
                  type="number"
                  min={5}
                  max={120}
                  value={durationMinutes}
                  onChange={(e) => setDurationMinutes(Number(e.target.value))}
                />
              </Field>

              <Field label="Answer mode" htmlFor="mode" hint="You can still type while in spoken mode">
                <Select id="mode" value={mode} onChange={(e) => setMode(e.target.value as ResponseMode)}>
                  <option value="typed">Typed answers</option>
                  <option value="spoken">Spoken answers (with typed fallback)</option>
                </Select>
              </Field>

              <Field label="Adaptive follow-ups" htmlFor="followups" hint="One probe question after some answers">
                <label className="flex items-center gap-2 py-2 text-sm text-ink-dim">
                  <input
                    id="followups"
                    type="checkbox"
                    checked={followUps}
                    onChange={(e) => setFollowUps(e.target.checked)}
                    className="h-4 w-4 accent-[var(--color-accent)]"
                  />
                  Enable follow-up questions
                </label>
              </Field>
            </div>
          </Card>

          <Card className="p-5">
            <h2 className="mb-1 text-sm font-semibold uppercase tracking-wide text-ink-faint">Optional context</h2>
            <p className="mb-4 text-xs text-ink-faint">
              Used only to tailor this interview. Resumes and job descriptions stay in your browser and are sent to the
              AI provider only when one is configured. The app never invents experience you did not provide.
            </p>
            <div className="space-y-4">
              <Field
                label="Job description"
                htmlFor="jd"
                error={findIssue(issues, 'jobDescription')}
                hint={`${jdWords} words · paste the posting for role-specific questions`}
              >
                <Textarea
                  id="jd"
                  value={jobDescription}
                  onChange={(e) => setJobDescription(e.target.value)}
                  maxLength={8000}
                  rows={5}
                  placeholder="Paste the job description (optional)…"
                />
              </Field>
              <Field label="Resume text" htmlFor="resume" error={findIssue(issues, 'resumeText')} hint={`${resumeWords} words`}>
                <Textarea
                  id="resume"
                  value={resumeText}
                  onChange={(e) => setResumeText(e.target.value)}
                  maxLength={8000}
                  rows={5}
                  placeholder="Paste your resume as plain text (optional)…"
                />
              </Field>
            </div>
          </Card>
        </div>

        <div className="space-y-4">
          <Card className="p-5">
            <h2 className="text-sm font-semibold uppercase tracking-wide text-ink-faint">Plan summary</h2>
            <dl className="mt-3 space-y-2 text-sm">
              <SummaryRow term="Role" value={role || '—'} />
              <SummaryRow term="Level" value={EXPERIENCE_LABELS.find((e) => e.value === experience)?.label ?? ''} />
              <SummaryRow term="Type" value={TYPE_LABELS.find((t) => t.value === type)?.label ?? ''} />
              <SummaryRow term="Difficulty" value={difficulty} />
              <SummaryRow term="Questions" value={String(questionCount)} />
              <SummaryRow term="Duration" value={`${durationMinutes} min`} />
              <SummaryRow term="Mode" value={mode === 'typed' ? 'Typed' : 'Spoken + typed'} />
              <SummaryRow term="Follow-ups" value={followUps ? 'On' : 'Off'} />
            </dl>
          </Card>

          {issues.length > 0 ? (
            <Card className="border-danger/40 p-4" >
              <h2 className="text-sm font-semibold text-danger">Fix before starting</h2>
              <ul className="mt-2 list-inside list-disc space-y-1 text-xs text-ink-dim">
                {issues.map((issue) => (
                  <li key={issue}>{issue}</li>
                ))}
              </ul>
            </Card>
          ) : null}

          {preview ? (
            <Card className="p-4">
              <div className="flex items-center gap-2">
                <Badge tone={preview.source === 'ai' ? 'success' : 'warn'}>
                  {preview.source === 'ai' ? 'AI generated' : 'Fallback bank'}
                </Badge>
                <span className="faint">{preview.count} questions</span>
              </div>
              <p className="mt-2 text-xs text-ink-dim">{preview.note}</p>
            </Card>
          ) : null}

          <Button type="submit" className="w-full py-3" disabled={generating}>
            {generating ? 'Generating your interview…' : 'Generate & start interview'}
          </Button>
          <p className="faint text-center">
            Questions come from the configured AI provider when available, otherwise from the curated fallback bank -
            always labelled.
          </p>
        </div>
      </form>
    </div>
  );
}

function SummaryRow({ term, value }: { term: string; value: string }) {
  return (
    <div className="flex items-start justify-between gap-3">
      <dt className="text-ink-faint">{term}</dt>
      <dd className="text-right text-ink">{value}</dd>
    </div>
  );
}

function findIssue(issues: string[], path: string): string | undefined {
  return issues.find((issue) => issue.startsWith(`${path}:`))?.split(': ').slice(1).join(': ');
}
