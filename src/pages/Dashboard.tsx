import { useMemo, useState, type FormEvent } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import {
  CheckCheck,
  Flame,
  Gauge,
  PlayCircle,
  Plus,
  Target,
  Timer,
} from 'lucide-react';
import {
  Badge,
  Button,
  Card,
  EmptyState,
  Field,
  Input,
  MetricCard,
  PageHeader,
  Select,
} from '../components/ui.js';
import { ScoreTrendChart } from '../components/charts.js';
import { summarizeHistory } from '../lib/analytics.js';
import { dashboardKpis, estimateMinutes, recentInterviewRows } from '../lib/dashboard.js';
import { startInterview } from '../lib/startInterview.js';
import { formatDuration } from '../lib/timer.js';
import type { Difficulty, InterviewConfig, InterviewType, ResponseMode } from '../lib/types.js';
import { useStore } from '../state/store.js';
import { useToast } from '../state/toast.js';

const STATUS_BADGE: Record<string, { tone: 'success' | 'accent' | 'neutral' | 'warn'; label: string }> = {
  completed: { tone: 'success', label: 'Completed' },
  'in-progress': { tone: 'accent', label: 'In progress' },
  'ended-early': { tone: 'neutral', label: 'Ended early' },
};

export default function Dashboard() {
  const { db, update } = useStore();
  const { push } = useToast();
  const navigate = useNavigate();

  const [goalTarget, setGoalTarget] = useState(5);
  const [goalScore, setGoalScore] = useState(70);

  // Quick-start state
  const [qsRole, setQsRole] = useState('');
  const [qsType, setQsType] = useState<InterviewType>('mixed');
  const [qsDifficulty, setQsDifficulty] = useState<Difficulty>('medium');
  const [qsCount, setQsCount] = useState(5);
  const [qsMode, setQsMode] = useState<ResponseMode>('typed');
  const [qsStarting, setQsStarting] = useState(false);

  const summary = useMemo(() => summarizeHistory(db.sessions), [db.sessions]);
  const kpis = useMemo(() => dashboardKpis(db.sessions), [db.sessions]);
  const rows = useMemo(() => recentInterviewRows(db.sessions), [db.sessions]);

  const inProgress = db.sessions.filter((s) => !['completed', 'abandoned'].includes(s.state));
  const firstName = db.profile?.name?.split(' ')[0] ?? 'there';
  const roleSuggestion = db.profile?.targetRole || db.sessions[0]?.config.role || '';

  function handleAddGoal() {
    const result = update((database) => ({
      ...database,
      goals: [
        {
          id: `goal_${Date.now()}`,
          label: `${goalTarget} interviews · avg ${goalScore}`,
          targetSessions: goalTarget,
          targetScore: goalScore,
          createdAt: new Date().toISOString(),
        },
        ...database.goals,
      ].slice(0, 20),
    }));
    if (result.ok) push('Goal added.', 'success');
    else push(result.error, 'error');
  }

  async function handleQuickStart(event: FormEvent) {
    event.preventDefault();
    const config: InterviewConfig = {
      role: (qsRole.trim() || db.profile?.targetRole || '').trim(),
      experience: 'mid',
      industry: '',
      type: qsType,
      difficulty: qsDifficulty,
      questionCount: qsCount,
      durationMinutes: estimateMinutes(qsCount, qsDifficulty),
      mode: qsMode,
      jobDescription: '',
      resumeText: '',
      followUps: true,
    };
    setQsStarting(true);
    try {
      const result = await startInterview(config);
      if (!result.ok) {
        if (result.issues?.length) {
          push(result.issues[0], 'error');
        } else {
          push(result.error ?? 'Could not start the interview.', 'error');
        }
        return;
      }
      push(
        result.source === 'ai'
          ? `Interview plan generated by ${result.model ?? 'the AI provider'}.`
          : result.note || 'Using the built-in fallback question bank.',
        result.source === 'ai' ? 'success' : 'warning',
      );
      navigate(`/interview/${result.sessionId}`);
    } finally {
      setQsStarting(false);
    }
  }

  return (
    <div>
      <PageHeader
        title={`Welcome back, ${firstName}`}
        subtitle="Your practice history, trends and next best actions."
        actions={
          <>
            <Link to="/interview/new" className="btn-primary">
              <Plus size={15} aria-hidden />
              New interview
            </Link>
            <Link to="/library" className="btn-secondary">
              Practice a question
            </Link>
          </>
        }
      />

      {inProgress.length > 0 ? (
        <Card className="mb-6 flex flex-wrap items-center justify-between gap-3 border-accent/40 p-4">
          <div>
            <p className="text-sm font-medium text-ink">
              You have {inProgress.length} interview{inProgress.length > 1 ? 's' : ''} in progress
            </p>
            <p className="faint mt-1">Pick up where you left off - drafts and progress are saved.</p>
          </div>
          <Link to={`/interview/${inProgress[0].id}`} className="btn-primary">
            Resume {inProgress[0].config.role}
          </Link>
        </Card>
      ) : null}

      {/* KPI row - every value derived from real sessions */}
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <MetricCard
          label="Completed interviews"
          value={kpis.completed}
          hint={`of ${kpis.totalSessions} total sessions`}
          icon={<CheckCheck size={17} />}
        />
        <MetricCard
          label="Practice time"
          value={formatDuration(kpis.practiceSeconds)}
          hint="active time across all sessions"
          icon={<Timer size={17} />}
        />
        <MetricCard
          label="Average score"
          value={kpis.averageScore ?? '—'}
          hint={
            kpis.averageScore !== null
              ? 'from evaluated answers'
              : 'complete an interview with evaluations'
          }
          delta={kpis.scoreDelta?.delta ?? null}
          icon={<Gauge size={17} />}
        />
        <MetricCard
          label="Day streak"
          value={kpis.streakDays}
          hint={kpis.streakDays > 0 ? 'consecutive days with practice' : 'practice today to start a streak'}
          icon={<Flame size={17} />}
        />
      </div>

      {/* Chart + quick start */}
      <div className="mt-6 grid gap-6 lg:grid-cols-3">
        <Card className="p-5 lg:col-span-2">
          {summary.trendAvailable ? (
            <ScoreTrendChart points={summary.trend} title="Overall score by session" />
          ) : (
            <div className="flex h-full min-h-[240px] flex-col justify-center">
              <h3 className="text-sm font-semibold text-ink">Score trend</h3>
              <p className="mt-2 text-sm text-ink-dim">{summary.trendNote}</p>
              <p className="mt-2 max-w-xl text-xs text-ink-faint">
                Trends are only shown with enough real history so the chart never overstates your progress.
              </p>
              {summary.completedSessions < 3 ? (
                <p className="mt-1 max-w-xl text-xs text-ink-faint">
                  Finish {3 - summary.completedSessions} more interview
                  {3 - summary.completedSessions === 1 ? '' : 's'} with evaluations to unlock the chart.
                </p>
              ) : null}
            </div>
          )}
        </Card>

        <Card className="p-5">
          <div className="flex items-center gap-2">
            <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-accent-soft text-accent-2">
              <PlayCircle size={16} aria-hidden />
            </span>
            <h3 className="text-sm font-semibold text-ink">Quick start</h3>
          </div>
          <p className="mt-2 text-xs text-ink-dim">
            One form, straight into a session. Or{' '}
            <Link to="/interview/new" className="text-accent-2 underline">
              use full setup
            </Link>{' '}
            for JD/resume context.
          </p>

          <form onSubmit={handleQuickStart} className="mt-4 space-y-3">
            <Field label="Target role" htmlFor="qs-role" hint="Used to pick relevant questions.">
              <Input
                id="qs-role"
                value={qsRole}
                onChange={(e) => setQsRole(e.target.value)}
                placeholder={roleSuggestion || 'e.g. Product Manager'}
              />
            </Field>
            <div className="grid grid-cols-2 gap-3">
              <Field label="Type" htmlFor="qs-type">
                <Select id="qs-type" value={qsType} onChange={(e) => setQsType(e.target.value as InterviewType)}>
                  <option value="mixed">Mixed</option>
                  <option value="hr">HR</option>
                  <option value="behavioral">Behavioral</option>
                  <option value="technical">Technical</option>
                  <option value="project">Project deep-dive</option>
                  <option value="situational">Situational</option>
                  <option value="role">Role-specific</option>
                </Select>
              </Field>
              <Field label="Difficulty" htmlFor="qs-difficulty">
                <Select
                  id="qs-difficulty"
                  value={qsDifficulty}
                  onChange={(e) => setQsDifficulty(e.target.value as Difficulty)}
                >
                  <option value="easy">Easy</option>
                  <option value="medium">Medium</option>
                  <option value="hard">Hard</option>
                </Select>
              </Field>
            </div>
            <div className="grid grid-cols-2 gap-3">
              <Field label="Questions" htmlFor="qs-count">
                <Select id="qs-count" value={String(qsCount)} onChange={(e) => setQsCount(Number(e.target.value))}>
                  <option value="3">3</option>
                  <option value="5">5</option>
                  <option value="8">8</option>
                </Select>
              </Field>
              <Field label="Answer mode" htmlFor="qs-mode">
                <Select id="qs-mode" value={qsMode} onChange={(e) => setQsMode(e.target.value as ResponseMode)}>
                  <option value="typed">Typed</option>
                  <option value="spoken">Voice</option>
                </Select>
              </Field>
            </div>

            <p className="faint">
              Estimated {estimateMinutes(qsCount, qsDifficulty)} min · {qsCount} questions · labelled as an estimate.
            </p>

            <Button type="submit" className="w-full" disabled={qsStarting}>
              {qsStarting ? 'Preparing…' : 'Start interview'}
            </Button>
          </form>
        </Card>
      </div>

      {/* Recent interviews + recommendations */}
      <div className="mt-6 grid gap-6 lg:grid-cols-3">
        <section className="lg:col-span-2">
          <div className="mb-3 flex items-center justify-between">
            <h2 className="text-lg font-semibold text-ink">Recent interviews</h2>
            <Link to="/history" className="text-sm text-accent-2 underline">
              View all
            </Link>
          </div>

          {rows.length === 0 ? (
            <EmptyState
              title="No sessions yet"
              description="Configure your first mock interview - it takes about a minute and you can answer by voice or text."
              action={
                <Link to="/interview/new" className="btn-primary">
                  Configure an interview
                </Link>
              }
            />
          ) : (
            <Card className="overflow-x-auto p-0">
              <table className="w-full min-w-[640px] text-left text-sm">
                <thead>
                  <tr className="border-b border-line text-[11px] uppercase tracking-wider text-ink-faint">
                    <th scope="col" className="px-4 py-3 font-semibold">
                      Interview
                    </th>
                    <th scope="col" className="px-3 py-3 font-semibold">
                      Date
                    </th>
                    <th scope="col" className="px-3 py-3 font-semibold">
                      Status
                    </th>
                    <th scope="col" className="px-3 py-3 font-semibold">
                      Score
                    </th>
                    <th scope="col" className="px-3 py-3 font-semibold">
                      Time
                    </th>
                    <th scope="col" className="px-3 py-3 font-semibold">
                      Progress
                    </th>
                    <th scope="col" className="px-4 py-3 text-right font-semibold">
                      <span className="sr-only">Actions</span>
                    </th>
                  </tr>
                </thead>
                <tbody>
                  {rows.map((row) => {
                    const badge = STATUS_BADGE[row.status];
                    return (
                      <tr key={row.id} className="border-b border-line last:border-0 hover:bg-panel-2/60">
                        <td className="px-4 py-3">
                          <p className="font-medium text-ink">{row.role}</p>
                          <p className="text-xs text-ink-faint">
                            {row.type} · {row.difficulty}
                          </p>
                        </td>
                        <td className="px-3 py-3 text-ink-dim">{row.date}</td>
                        <td className="px-3 py-3">
                          <Badge tone={badge.tone === 'neutral' ? 'neutral' : badge.tone}>{badge.label}</Badge>
                        </td>
                        <td className="px-3 py-3">
                          {row.score !== null ? (
                            <span className={`font-semibold ${row.score >= 70 ? 'text-success' : row.score >= 50 ? 'text-ink' : 'text-warn'}`}>
                              {row.score}
                            </span>
                          ) : (
                            <span className="text-ink-faint">—</span>
                          )}
                        </td>
                        <td className="px-3 py-3 text-ink-dim">{formatDuration(row.durationSeconds)}</td>
                        <td className="px-3 py-3 text-ink-dim">
                          {row.answeredCount}/{row.questionCount}
                        </td>
                        <td className="px-4 py-3 text-right">
                          {row.status === 'in-progress' ? (
                            <Link to={`/interview/${row.id}`} className="btn-secondary h-8 px-3 text-xs">
                              Resume
                            </Link>
                          ) : (
                            <Link to={`/report/${row.id}`} className="btn-ghost h-8 px-3 text-xs">
                              Report
                            </Link>
                          )}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </Card>
          )}
        </section>

        <Card className="h-fit p-5">
          <h3 className="text-sm font-semibold text-ink">Recommended next practice</h3>
          {summary.recommendedAreas.length > 0 ? (
            <ul className="mt-3 space-y-2 text-sm text-ink-dim">
              {summary.recommendedAreas.map((area) => (
                <li key={area} className="flex items-center justify-between gap-2">
                  <span>{area}</span>
                  <Link to="/library" className="text-xs text-accent-2 underline">
                    practise
                  </Link>
                </li>
              ))}
            </ul>
          ) : (
            <p className="mt-2 text-sm text-ink-dim">
              {summary.completedSessions === 0
                ? 'Finish an interview to unlock skill-based recommendations.'
                : 'No weak skill areas detected yet - try a harder difficulty or a new interview type.'}
            </p>
          )}

          <div className="mt-5 border-t border-line pt-4">
            <h3 className="flex items-center gap-1.5 text-sm font-semibold text-ink">
              <Target size={14} aria-hidden /> Personal goals
            </h3>
            {db.goals.length === 0 ? (
              <p className="mt-2 text-xs text-ink-faint">No goals yet.</p>
            ) : (
              <ul className="mt-2 space-y-2">
                {db.goals.map((goal) => {
                  const progress = Math.min(summary.completedSessions, goal.targetSessions);
                  return (
                    <li key={goal.id} className="rounded-lg border border-line bg-panel-2 p-3">
                      <div className="flex items-center justify-between gap-2">
                        <span className="text-sm text-ink">{goal.label}</span>
                        <button
                          type="button"
                          className="text-xs text-ink-faint hover:text-danger"
                          onClick={() =>
                            update((d) => ({ ...d, goals: d.goals.filter((g) => g.id !== goal.id) }))
                          }
                          aria-label={`Remove goal ${goal.label}`}
                        >
                          ✕
                        </button>
                      </div>
                      <div className="mt-2 h-1.5 overflow-hidden rounded-full bg-panel">
                        <div
                          className="h-full bg-accent"
                          style={{ width: `${(progress / Math.max(1, goal.targetSessions)) * 100}%` }}
                        />
                      </div>
                      <p className="faint mt-1">
                        {progress}/{goal.targetSessions} interviews · target avg {goal.targetScore}
                      </p>
                    </li>
                  );
                })}
              </ul>
            )}
            <div className="mt-3 grid grid-cols-2 gap-2">
              <Field label="Interviews" htmlFor="goal-sessions">
                <Input
                  id="goal-sessions"
                  type="number"
                  min={1}
                  max={100}
                  value={goalTarget}
                  onChange={(e) => setGoalTarget(Number(e.target.value))}
                />
              </Field>
              <Field label="Avg score" htmlFor="goal-score">
                <Input
                  id="goal-score"
                  type="number"
                  min={1}
                  max={100}
                  value={goalScore}
                  onChange={(e) => setGoalScore(Number(e.target.value))}
                />
              </Field>
            </div>
            <Button variant="secondary" className="mt-2 w-full" onClick={handleAddGoal}>
              Add goal
            </Button>
          </div>
        </Card>
      </div>

      {summary.notes.length > 0 ? (
        <Card className="mt-6 border-warn/30 p-4">
          <ul className="space-y-1 text-xs text-warn">
            {summary.notes.map((note) => (
              <li key={note}>{note}</li>
            ))}
          </ul>
        </Card>
      ) : null}
    </div>
  );
}
