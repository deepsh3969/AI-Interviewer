import { z } from 'zod';
import { chatJson } from '../server/ai';
import { respondProviderFailure } from '../server/failures';
import {
  RateLimiter,
  clientIp,
  fail,
  json,
  methodNotAllowed,
  readJsonBody,
  type ApiHandler,
} from '../server/http';
import { aiConfig } from '../server/env';
import { aiQuestionSetSchema, questionGenerationMessages } from '../server/prompts';
import { validateConfig, interviewQuestionSchema } from '../src/lib/validation';
import { buildCriteria } from '../src/lib/rubrics';
import { hashString } from '../src/lib/id';
import type { Difficulty, InterviewQuestion } from '../src/lib/types';

const limiter = new RateLimiter(60_000, 12);

const requestSchema = z.object({ config: z.unknown() });

const DIFF_ORDER: Record<Difficulty, number> = { easy: 0, medium: 1, hard: 2 };

function clampDifficulty(d: Difficulty, target: Difficulty): Difficulty {
  const order: Difficulty[] = ['easy', 'medium', 'hard'];
  const t = DIFF_ORDER[target];
  const v = Math.max(t - 1, Math.min(t + 1, DIFF_ORDER[d]));
  return order[v];
}

const handler: ApiHandler = async (req, res) => {
  if (req.method !== 'POST') return methodNotAllowed(res, ['POST']);

  const ip = clientIp(req);
  if (limiter.check(ip)) {
    res.setHeader('Retry-After', '60');
    return fail(res, 429, 'rate_limited', 'Too many question-generation requests. Try again in a minute.');
  }

  const body = await readJsonBody(req);
  if (!body.ok) {
    return fail(
      res,
      body.reason === 'too_large' ? 413 : 400,
      'invalid_request',
      body.reason === 'too_large' ? 'Request body is too large.' : 'Request body must be valid JSON.',
    );
  }

  const parsedBody = requestSchema.safeParse(body.value);
  if (!parsedBody.success) {
    return fail(res, 400, 'invalid_request', 'Expected { config } in the request body.');
  }

  const config = validateConfig(parsedBody.data.config);
  if (!config.ok) {
    return fail(res, 400, 'invalid_request', 'Interview configuration is invalid.', { issues: config.issues });
  }

  if (!aiConfig().configured) {
    return fail(
      res,
      503,
      'ai_not_configured',
      'AI question generation is not configured on this deployment. The client will use the built-in fallback question bank.',
    );
  }

  try {
    const { system, user } = questionGenerationMessages(config.value);
    const { data, model } = await chatJson({
      system,
      user,
      schema: aiQuestionSetSchema,
      maxTokens: 4000,
      temperature: 0.6,
    });

    const questions: InterviewQuestion[] = [];
    const seen = new Set<string>();
    for (const [index, raw] of data.questions.entries()) {
      const text = raw.text.trim();
      const key = text.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
      if (seen.has(key)) continue;
      seen.add(key);
      const candidate: InterviewQuestion = {
        id: `ai_${hashString(`${text}|${index}`)}`,
        text,
        category: raw.category,
        difficulty: clampDifficulty(raw.difficulty, config.value.difficulty),
        skill: raw.skill.trim(),
        criteria: buildCriteria(raw.criteria.map((c) => c.label)),
        answerStructure: raw.answerStructure.map((s) => s.trim()),
        source: 'ai',
        timeLimitSeconds: raw.timeLimitSeconds ?? 180,
      };
      const check = interviewQuestionSchema.safeParse(candidate);
      if (check.success) questions.push(check.data);
      if (questions.length >= config.value.questionCount) break;
    }

    if (questions.length === 0) {
      return fail(res, 502, 'upstream_error', 'The AI provider returned no usable questions.');
    }

    return json(res, 200, {
      questions,
      source: 'ai',
      model,
      note: `${questions.length} questions generated by the configured AI provider.`,
    });
  } catch (err) {
    return respondProviderFailure(res, err);
  }
};

export default handler;
